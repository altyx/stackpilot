// Publishes the app's legal texts as Markdown in docs/legal.
//
// The app displays src/legal; the stores require a public URL for the
// privacy policy. Generating one from the other guarantees both say the
// same thing.
//
//   npm run legal              regenerates docs/legal
//   npm run legal -- --check   fails if docs/legal is stale (CI)

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { registerHooks } from 'node:module';
import path from 'node:path';

// Node runs .ts files by stripping types, but requires the extension in
// imports; src/legal imports without one, as Metro allows.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith('.') && path.extname(specifier) === '') {
      return nextResolve(`${specifier}.ts`, context);
    }
    return nextResolve(specifier, context);
  },
});

const { TERMS } = await import('../src/legal/terms.ts');
const { PRIVACY } = await import('../src/legal/privacy.ts');

const ROOT = path.resolve(import.meta.dirname, '..');
const OUTPUTS = [
  { file: 'docs/legal/terms.md', document: TERMS },
  { file: 'docs/legal/privacy.md', document: PRIVACY },
];

/** Neutralizes Markdown syntax: the text must display exactly as written. */
function escape(text) {
  return text.replace(/[\\`*_[\]<>]/g, '\\$&');
}

function toMarkdown(document) {
  const lines = [
    '<!-- Generated by scripts/legal-markdown.mjs from src/legal: do not hand-edit. -->',
    '',
    `# ${escape(document.title)}`,
    '',
    `_Dernière mise à jour : ${escape(document.updatedAt)}_`,
    '',
    escape(document.intro),
  ];
  document.sections.forEach((section, index) => {
    lines.push('', `## ${index + 1}. ${escape(section.title)}`);
    for (const block of section.body) {
      lines.push('');
      if (typeof block === 'string') lines.push(escape(block));
      else lines.push(...block.map((item) => `- ${escape(item)}`));
    }
  });
  return `${lines.join('\n')}\n`;
}

const check = process.argv.includes('--check');
const stale = [];

for (const { file, document } of OUTPUTS) {
  const target = path.join(ROOT, file);
  const expected = toMarkdown(document);
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => null);
    if (current !== expected) stale.push(file);
    continue;
  }
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, expected);
  console.log(`${file} généré`);
}

if (stale.length > 0) {
  console.error(`Textes légaux publiés à régénérer (npm run legal) : ${stale.join(', ')}`);
  process.exit(1);
}
